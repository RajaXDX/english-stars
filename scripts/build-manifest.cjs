// يبني audio/manifest.js: مفتاح العبارة → اسم ملفها لكل صوت (audio/m و audio/f).
// يفضّل الاسم الجديد (fileId(key)) ثم الاسم القديم لنفس النص. لا يحذف أي ملف.
// الاستخدام: node scripts/build-manifest.cjs [--voice-info m="..." f="..."]
const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const root = path.join(__dirname, "..");
const entries = JSON.parse(execFileSync(process.execPath, [path.join(__dirname, "collect-narration.cjs")], { maxBuffer: 64 << 20 }));
const VOICES = ["m", "f"];
const INFO_FILE = path.join(root, "audio", "voices.json");      // وصف مصدر كل صوت (يكتبه المولّد)
const info = fs.existsSync(INFO_FILE) ? JSON.parse(fs.readFileSync(INFO_FILE, "utf8")) : {};

const have = {};
for (const v of VOICES) {
  const dir = path.join(root, "audio", v);
  have[v] = new Set(fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => /^[a-f0-9]{16}\.mp3$/.test(f)) : []);
}

const clips = {};
const stats = { fresh: 0, legacy: 0, missing: [] };
for (const e of entries) {
  const pick = {};
  for (const v of VOICES) {
    if (have[v].has(e.file)) { pick[v] = e.file; stats.fresh++; }
    else if (have[v].has(e.legacy)) { pick[v] = e.legacy; stats.legacy++; }
  }
  if (!pick.m && !pick.f) { stats.missing.push(e.key); continue; }
  const ids = VOICES.map(v => pick[v] ? pick[v].slice(0, 16) : "");
  clips[e.key] = ids[0] === ids[1] ? ids[0] : ids;           // نفس الاسم للصوتين → نص واحد
}

const manifest = { version: 2, language: "en-US", voices: info, clips };
const out = path.join(root, "audio", "manifest.js");
const tmp = out + ".tmp";
fs.writeFileSync(tmp, "// Generated by scripts/build-manifest.cjs — do not edit by hand.\n" +
  "globalThis.NARRATION_AUDIO = " + JSON.stringify(manifest) + ";\n");
fs.renameSync(tmp, out);
console.log(`manifest: ${Object.keys(clips).length} phrases · new-name files ${stats.fresh} · legacy files ${stats.legacy} · missing ${stats.missing.length}`);
if (stats.missing.length) { console.error("Phrases with no recording: " + stats.missing.slice(0, 20).join(" | ")); process.exitCode = 1; }
